#!/usr/bin/env node
/**
 * Generates backend/db/05-productive-question-bank.sql from the practice banks
 * in src/data/questionBank.ts.
 *
 * Only the productive tasks are imported (photo description, interactive
 * writing, writing sample, speaking sample): their server payload is a prompt,
 * so they need no answer-key mapping and cannot break server-side grading.
 *
 * The practice banks are much richer than the original 191-item seed (2 speaking
 * prompts per type), which made every mock test repeat the same tasks.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'src/data/questionBank.ts'), 'utf8');

function extractArray(name) {
  const marker = new RegExp(`export const ${name}[^=]*=\\s*\\[`);
  const match = marker.exec(source);
  if (!match) throw new Error(`array ${name} not found`);
  const start = match.index + match[0].length - 1;
  let depth = 0;
  for (let index = start; index < source.length; index += 1) {
    if (source[index] === '[') depth += 1;
    else if (source[index] === ']') {
      depth -= 1;
      if (depth === 0) return JSON.parse(source.slice(start, index + 1));
    }
  }
  throw new Error(`array ${name} is not terminated`);
}

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => sqlString(JSON.stringify(value));

const rows = [];

for (const item of extractArray('speakPhotoBank')) {
  rows.push({
    id: `bank${item.id}`,
    type: 'SPEAK_PHOTO',
    difficulty: item.difficulty,
    timeLimit: item.speakTimeSec || 90,
    content: {
      imageUrl: item.imageUrl,
      prompt: `Describe the image in detail (${item.topic}). Mention the people, the setting and the atmosphere. Key ideas: ${(item.keyThemes || []).join('; ')}.`,
      altText: item.altText,
    },
    correct: { rubric: 'fluency_pronunciation_vocabulary_min90s' },
  });
}

for (const item of extractArray('speakingSampleBank')) {
  rows.push({
    id: `bank${item.id}`,
    type: 'SPEAKING_SAMPLE',
    difficulty: item.difficulty,
    timeLimit: item.speakTimeSec || 180,
    content: { prompt: item.prompt, topic: item.topic },
    correct: { rubric: 'extended_discourse_academic_speech_min180s' },
  });
}

for (const item of extractArray('writingSampleBank')) {
  rows.push({
    id: `bank${item.id}`,
    type: 'WRITING_SAMPLE',
    difficulty: item.difficulty,
    timeLimit: 300,
    content: { prompt: item.prompt },
    correct: { rubric: 'academic_argumentation_min100' },
  });
}

for (const item of extractArray('interactiveWritingBank')) {
  rows.push({
    id: `bank${item.id}`,
    type: 'INTERACTIVE_WRITING',
    difficulty: item.difficulty,
    timeLimit: 480,
    content: { part1Prompt: item.part1Prompt, part2Prompt: item.part2Prompt, prompt: item.part1Prompt },
    correct: { rubric: 'interactive_writing_two_parts' },
  });
}

for (const item of extractArray('writePhotoBank')) {
  rows.push({
    id: `bank${item.id}`,
    type: 'WRITE_PHOTO',
    difficulty: item.difficulty,
    timeLimit: 60,
    content: {
      imageUrl: item.imageUrl,
      prompt: `Describe this image in 3–4 sentences. Context: ${item.altText}.`,
      altText: item.altText,
    },
    correct: { rubric: 'written_description_min_3_sentences' },
  });
}

const lines = [];
lines.push('-- Generated by scripts/sync_question_bank.mjs. Do not edit by hand.');
lines.push('-- Productive-skill tasks imported from the practice banks so a mock test');
lines.push('-- does not repeat the same two prompts. Ids are prefixed with "bank"');
lines.push('-- and the insert never overwrites an existing row.');
lines.push('');

for (const row of rows) {
  lines.push('INSERT INTO questions (id, type, difficulty_band, content_payload, correct_answers, time_limit_sec, is_active)');
  lines.push('VALUES (');
  lines.push(`  ${sqlString(row.id)},`);
  lines.push(`  ${sqlString(row.type)},`);
  lines.push(`  ${sqlString(row.difficulty)},`);
  lines.push(`  ${json(row.content)},`);
  lines.push(`  ${json(row.correct)},`);
  lines.push(`  ${row.timeLimit},`);
  lines.push('  true');
  lines.push(')');
  lines.push('ON CONFLICT (id) DO NOTHING;');
  lines.push('');
}

const target = path.join(root, 'backend/db/05-productive-question-bank.sql');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('backend/db/05-productive-question-bank.sql is out of date; run node scripts/sync_question_bank.mjs');
    process.exit(1);
  }
  console.log(`question bank seed is up to date (${rows.length} questions)`);
  process.exit(0);
}

fs.writeFileSync(target, output, 'utf8');
console.log(`wrote ${rows.length} questions to ${target}`);
