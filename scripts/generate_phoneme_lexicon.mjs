const entries = new Map();
const add = (word, ipa) => {
  const key = String(word ?? '').trim().toLowerCase().replace(/[^a-z'-]/g, '');
  const value = String(ipa ?? '').trim();
  if (!key || !value.startsWith('/') || !value.endsWith('/')) return;
  if (!entries.has(key)) entries.set(key, value);
};

Object.entries(CORE).forEach(([word, ipa]) => add(word, ipa));

const dictionary = fs.readFileSync(path.join(root, 'backend/db/10-dictionary.sql'), 'utf8');
for (const match of dictionary.matchAll(/\('dict-\d+', '((?:[^']|'')*)', '([^']*)'/g)) {
  add(match[1].replace(/''/g, "'"), match[2]);
}

const memorySeed = JSON.parse(
  fs.readFileSync(path.join(root, 'backend/internal/repository/memory/vocabulary_seed.json'), 'utf8')
);
for (const row of memorySeed) add(row.word, row.ipa);

const sorted = [...entries.entries()].sort(([left], [right]) => left.localeCompare(right));
const lines = sorted.map(([word, ipa]) => `  ${JSON.stringify(word)}: ${JSON.stringify(ipa)},`);
const output = `// Generated by scripts/generate_phoneme_lexicon.mjs. Do not edit by hand.
//
// IPA for the course vocabulary plus a core of high-frequency words. The
// fallback in phonemes.ts handles words that are not listed here.

export const PHONEME_LEXICON: Record<string, string> = {
${lines.join('\n')}
};
`;
const target = path.join(root, 'src/lib/phonemeLexicon.ts');
fs.writeFileSync(target, output);
console.log(`wrote ${path.relative(root, target)} (${sorted.length} words)`);
