#!/usr/bin/env node
/**
 * Generates backend/db/06-level-bank.sql from scripts/content/level-bank.mjs.
 *
 * Per level (A1..C2):
 *   100 Read & Select  — 20 curated real words + 80 generated pseudo-words
 *    20 Fill in the Blanks
 *    20 Listen and Type
 *
 * The generated rows are prompt-only or use the same payload shape as the
 * existing seed, so server-side grading keeps working unchanged.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { words, fillBlanks, listenSentences } from './content/level-bank.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const LEVELS = ['A1', 'A2', 'B1', 'B2', 'C1', 'C2'];

const sqlString = (value) => `'${String(value).replace(/'/g, "''")}'`;
const json = (value) => sqlString(JSON.stringify(value));

const realWords = new Set();
for (const level of LEVELS) {
  for (const word of words[level].split(/\s+/)) realWords.add(word.toLowerCase());
}

const VOWELS = new Set(['a', 'e', 'i', 'o', 'u']);

/** Deterministic pseudo-word mutations that stay pronounceable but are not words. */
function pseudoVariants(word) {
  const lower = word.toLowerCase();
  const variants = [];

  // 1. swap two adjacent letters in the middle
  if (lower.length >= 4) {
    const index = Math.floor(lower.length / 2);
    variants.push(lower.slice(0, index - 1) + lower[index] + lower[index - 1] + lower.slice(index + 1));
  }
  // 2. replace the first vowel with "u" (or "a" when it is already u)
  const vowelIndex = [...lower].findIndex((letter) => VOWELS.has(letter));
  if (vowelIndex >= 0) {
    const replacement = lower[vowelIndex] === 'u' ? 'a' : 'u';
    variants.push(lower.slice(0, vowelIndex) + replacement + lower.slice(vowelIndex + 1));
  }
  // 3. stem + "ic"
  variants.push(lower.slice(0, Math.max(3, lower.length - 2)) + 'ic');
  // 4. final letter replaced with "x"
  variants.push(lower.slice(0, -1) + 'x');

  return variants;
}

const rows = [];
const counters = { READ_SELECT: 0, FILL_BLANKS: 0, LISTEN_TYPE: 0 };
const prefixes = { READ_SELECT: 'lvlrs', FILL_BLANKS: 'lvlfb', LISTEN_TYPE: 'lvllt' };
function nextId(type) {
  counters[type] += 1;
  return `${prefixes[type]}-${counters[type]}`;
}

for (const level of LEVELS) {
  const levelWords = words[level].split(/\s+/).filter(Boolean);

  for (const word of levelWords) {
    rows.push({
      id: nextId('READ_SELECT'),
      type: 'READ_SELECT',
      level,
      time: 5,
      content: { word },
      correct: { isReal: true },
    });
  }

  const pseudo = [];
  for (const word of levelWords) {
    for (const variant of pseudoVariants(word)) {
      if (variant.length < 4) continue;
      if (realWords.has(variant) || pseudo.includes(variant)) continue;
      pseudo.push(variant);
    }
  }
  // 80 pseudo-words per level; cycle the mutations if a word produced fewer.
  for (let index = 0; index < 80; index += 1) {
    const candidate = pseudo[index] || `${levelWords[index % levelWords.length].toLowerCase()}sh`;
    rows.push({
      id: nextId('READ_SELECT'),
      type: 'READ_SELECT',
      level,
      time: 5,
      content: { word: candidate },
      correct: { isReal: false },
    });
  }

  fillBlanks[level].forEach(([before, word, after], index) => {
    const prefixLength = Math.min(3, Math.max(2, word.length - 1));
    const prefix = word.slice(0, prefixLength);
    rows.push({
      id: nextId('FILL_BLANKS'),
      type: 'FILL_BLANKS',
      level,
      time: 20,
      content: {
        fullWord: word,
        givenPrefix: prefix,
        totalLength: word.length,
        sentenceBefore: before,
        sentenceAfter: after,
      },
      correct: { fullWord: word, missingLetters: word.slice(prefixLength) },
    });
  });

  listenSentences[level].forEach((sentence, index) => {
    rows.push({
      id: nextId('LISTEN_TYPE'),
      type: 'LISTEN_TYPE',
      level,
      time: 60,
      content: { playsAllowed: 3, audioSentence: sentence },
      correct: { expectedSentence: sentence },
    });
  });
}

// The content lint expects ids shaped like "letters-digits".
const lines = [];
lines.push('-- Generated by scripts/generate_level_bank.mjs. Do not edit by hand.');
lines.push('-- A1–C2 level bank: Read & Select (real + pseudo), Fill in the Blanks,');
lines.push('-- Listen and Type. Per level: 100 / 20 / 20 items.');
lines.push('');

for (const row of rows) {
  lines.push('INSERT INTO questions (id, type, difficulty_band, content_payload, correct_answers, time_limit_sec, is_active)');
  lines.push('VALUES (');
  lines.push(`  ${sqlString(row.id)},`);
  lines.push(`  ${sqlString(row.type)},`);
  lines.push(`  ${sqlString(row.level)},`);
  lines.push(`  ${json(row.content)},`);
  lines.push(`  ${json(row.correct)},`);
  lines.push(`  ${row.time},`);
  lines.push('  true');
  lines.push(')');
  lines.push('ON CONFLICT (id) DO NOTHING;');
  lines.push('');
}

const target = path.join(root, 'backend/db/06-level-bank.sql');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== output) {
    console.error('backend/db/06-level-bank.sql is out of date; run node scripts/generate_level_bank.mjs');
    process.exit(1);
  }
  console.log(`level bank is up to date (${rows.length} questions)`);
  process.exit(0);
}

fs.writeFileSync(target, output, 'utf8');
const perLevel = {};
for (const row of rows) {
  perLevel[row.level] = perLevel[row.level] || { READ_SELECT: 0, FILL_BLANKS: 0, LISTEN_TYPE: 0 };
  perLevel[row.level][row.type] += 1;
}
console.log(`wrote ${rows.length} questions to ${target}`);
console.log(perLevel);
