#!/usr/bin/env python3
"""Extracts learning content from the `theory/` course materials.

Sources:
  theory/HEDWIG-VOCABULARY.docx      → real English words used by the Read &
                                       Select vocabulary tests;
  theory/Difficult Dictation 20 Tests.pdf → 20 dictation sentences.

Outputs:
  src/data/theoryVocabulary.ts       → the word list for the Vocabulary tab;
  backend/db/07-theory-content.sql   → Listen & Type items for the trainers.

The PDF extraction needs `pypdf` (pip install pypdf). Four sentences are
corrected by hand because the PDF text layer joins words ("wouldhave").
"""
import json
import re
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Sentences that the PDF text layer glues together; corrected against the page.
SENTENCE_FIXES = {
    "Many large university institutions are now starting to offer free online courses":
        "Many large university institutions are now starting to offer free online courses.",
    "Developments in technology and transportation infrastructurehave made tourism more affordable.":
        "Developments in technology and transportation infrastructure have made tourism more affordable.",
    "I wouldhave bought you a present ifI hadknown it was your birthday.":
        "I would have bought you a present if I had known it was your birthday.",
}


def docx_words(path: Path) -> list[str]:
    with zipfile.ZipFile(path) as archive:
        xml = archive.read("word/document.xml").decode("utf-8")
    text = re.sub(r"<w:tab[^>]*/>", "\t", xml)
    text = re.sub(r"</w:p>", "\n", text)
    text = re.sub(r"<[^>]+>", "", text)
    text = text.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")

    words: list[str] = []
    seen: set[str] = set()
    for line in text.split("\n"):
        for raw in line.split(","):
            word = raw.strip().strip(".").strip()
            if not re.fullmatch(r"[A-Za-z][A-Za-z\- ]{2,}", word):
                continue
            # Multi-word entries are allowed, but keep them short.
            if len(word) > 24 or len(word.split()) > 2:
                continue
            key = word.lower()
            if key in seen:
                continue
            seen.add(key)
            words.append(word[0].upper() + word[1:].lower() if len(word.split()) == 1 else word)
    return words


def dictation_sentences(path: Path) -> list[str]:
    from pypdf import PdfReader

    reader = PdfReader(str(path))
    text = "\n".join((page.extract_text() or "") for page in reader.pages)
    blocks = re.split(r"Type the statement that you hear", text)

    sentences: list[str] = []
    for block in blocks[1:]:
        lines = [line.strip() for line in block.split("\n") if line.strip() and line.strip() != "TEST"]
        chunk: list[str] = []
        for line in lines:
            if re.fullmatch(r"TEST\s+\d+", line) or re.fullmatch(r"\d+", line):
                break
            chunk.append(line)
            if line.endswith((".", "?", "!")):
                break
        sentence = re.sub(r"\s+", " ", " ".join(chunk)).strip()
        sentence = SENTENCE_FIXES.get(sentence, sentence)
        if 20 <= len(sentence) <= 220 and sentence.endswith((".", "?", "!")):
            sentences.append(sentence)
    return sentences


def main() -> None:
    words = docx_words(ROOT / "theory/HEDWIG-VOCABULARY.docx")
    sentences = dictation_sentences(ROOT / "theory/Difficult Dictation 20 Tests.pdf")

    ts_path = ROOT / "src/data/theoryVocabulary.ts"
    ts_path.write_text(
        "// Generated by scripts/extract_theory_content.py. Do not edit by hand.\n"
        "// Source: theory/HEDWIG-VOCABULARY.docx.\n"
        f"export const theoryWords: string[] = {json.dumps(words, ensure_ascii=False, indent=0)};\n\n"
        "export const theoryVocabularyMeta = {\n"
        '  source: "theory/HEDWIG-VOCABULARY.docx",\n'
        f"  count: {len(words)},\n"
        "};\n",
        encoding="utf-8",
    )

    lines = [
        "-- Generated by scripts/extract_theory_content.py. Do not edit by hand.",
        "-- Source: theory/Difficult Dictation 20 Tests.pdf (20 tests).",
        "",
    ]
    for index, sentence in enumerate(sentences, 1):
        payload = json.dumps({"playsAllowed": 3, "audioSentence": sentence}, ensure_ascii=False)
        correct = json.dumps({"expectedSentence": sentence}, ensure_ascii=False)
        escaped_payload = payload.replace("'", "''")
        escaped_correct = correct.replace("'", "''")
        lines.extend([
            "INSERT INTO questions (id, type, difficulty_band, content_payload, correct_answers, time_limit_sec, is_active)",
            "VALUES (",
            f"  'thdict-{index}',",
            "  'LISTEN_TYPE',",
            "  'B2',",
            f"  '{escaped_payload}',",
            f"  '{escaped_correct}',",
            "  60,",
            "  true",
            ")",
            "ON CONFLICT (id) DO NOTHING;",
            "",
        ])
    (ROOT / "backend/db/07-theory-content.sql").write_text("\n".join(lines), encoding="utf-8")

    print(f"words: {len(words)} -> {ts_path}")
    print(f"dictations: {len(sentences)} -> backend/db/07-theory-content.sql")


if __name__ == "__main__":
    main()
