// ErrDailyLimitReached is returned when the student has used the daily
// allowance for an expensive action (a full mock or a speaking task).
var ErrDailyLimitReached = errors.New("daily limit reached")

// SpeakingQuestionTypes are the server question types that consume the daily
// speaking allowance.
var SpeakingQuestionTypes = []string{
	"SPEAK_PHOTO", "READ_THEN_SPEAK", "INTERACTIVE_SPEAKING", "SPEAKING_SAMPLE",
}

func envLimit(name string, fallback int) int {
	raw := os.Getenv(name)
	if raw == "" {
		return fallback
	}
	value, err := strconv.Atoi(raw)
	if err != nil {
		return fallback
	}
	if value <= 0 {
		return 0 // explicitly unlimited
	}
	return value
}

func envFloat(name string, fallback float64) float64 {
	raw := os.Getenv(name)
	if raw == "" {
		return fallback
	}
	value, err := strconv.ParseFloat(raw, 64)
	if err != nil || value < 0 {
		return fallback
	}
	return value
}

func envOrString(name, fallback string) string {
	if value := os.Getenv(name); value != "" {
		return value
	}
	return fallback
}

func startOfUTCDay() time.Time {
	now := time.Now().UTC()
	return time.Date(now.Year(), now.Month(), now.Day(), 0, 0, 0, 0, time.UTC)
}

func isSpeakingType(questionType string) bool {
	for _, speakingType := range SpeakingQuestionTypes {
		if speakingType == questionType {
			return true
		}
	}
	return false
}

// checkMockDailyLimit enforces DAILY_MOCK_LIMIT (default 3) for full mocks.
func checkMockDailyLimit(ctx context.Context, repo repository.TestSessionRepository, userID string) error {
	limit := envLimit("DAILY_MOCK_LIMIT", 3)
	if limit == 0 {
		return nil
	}
	used, err := repo.CountUserSessionsSince(ctx, userID, startOfUTCDay())
	if err != nil {
		return err
	}
	if used >= limit {
		return ErrDailyLimitReached
	}
	return nil
}

// checkSpeakingDailyLimit enforces DAILY_SPEAKING_LIMIT (default 20) for
// speaking practice tasks.
func checkSpeakingDailyLimit(ctx context.Context, repo repository.StudyRepository, userID string) error {
	limit := envLimit("DAILY_SPEAKING_LIMIT", 20)
	if limit == 0 || userID == "" {
		return nil
	}
	used, err := repo.CountPracticeAttemptsSince(ctx, userID, startOfUTCDay(), SpeakingQuestionTypes)
	if err != nil {
		return err
	}
	if used >= limit {
		return ErrDailyLimitReached
	}
	return nil
}

// GetDailyLimits reports the remaining allowance for the UI.
func (s *StudyService) GetDailyLimits(ctx context.Context, userID string) (*models.DailyLimits, error) {
	if s == nil || userID == "" {
		return &models.DailyLimits{Date: startOfUTCDay().Format("2006-01-02")}, nil
	}
	since := startOfUTCDay()
	limits := &models.DailyLimits{Date: since.Format("2006-01-02")}

	if s.catService != nil {
		limits.MockLimit = envLimit("DAILY_MOCK_LIMIT", 3)
		if used, err := s.catService.sessionRepo.CountUserSessionsSince(ctx, userID, since); err == nil {
			limits.MockUsed = used
		}
	}

	limits.SpeakingLimit = envLimit("DAILY_SPEAKING_LIMIT", 20)
	if used, err := s.storage.Study().CountPracticeAttemptsSince(ctx, userID, since, SpeakingQuestionTypes); err == nil {
		limits.SpeakingUsed = used
	}
	return limits, nil
}

// Daily limit scopes. The per-user allowance of the mock and speaking scopes
// keeps using the activity tables; the guard adds independent IP and device
// allowances so creating a new account or clearing cookies does not reset the
// expensive quota.
const (
	LimitScopeMock     = "mock"
	LimitScopeSpeaking = "speaking"
	LimitScopeAuth     = "auth"
)

// LimitExceededError reports one exhausted quota dimension.
type LimitExceededError struct {
	Scope string
	Kind  string // "ip" or "device"
	Limit int
	Used  int
}

func (e *LimitExceededError) Error() string {
	return fmt.Sprintf("%s daily limit reached (%s: %d/%d)", e.Scope, e.Kind, e.Used, e.Limit)
}

// IsSpeakingQuestionType reports whether a question consumes the speaking
// allowance. It is exported so HTTP handlers can apply the IP/device guard
// using the server-resolved type rather than the client-supplied one.
func IsSpeakingQuestionType(questionType string) bool {
	return isSpeakingType(questionType)
}

// ValidDeviceID validates the untrusted X-Device-Id header. The value is a
// random identifier generated by the browser; length and charset are bounded
// before it is hashed so it can never be used as a log injection or storage
// amplification vector.
func ValidDeviceID(deviceID string) bool {
	if deviceID == "" || len(deviceID) > 128 {
		return false
	}
	for index := 0; index < len(deviceID); index++ {
		char := deviceID[index]
		switch {
		case char >= 'a' && char <= 'z':
		case char >= 'A' && char <= 'Z':
		case char >= '0' && char <= '9':
		case char == '.', char == '_', char == ':', char == '-':
		default:
			return false
		}
	}
	return true
}

// HashDeviceID returns a keyed hash of the device identifier. The raw value is
// never stored or logged; rotating the header produces a different hash, but
// the independent IP allowance still bounds the caller.
func HashDeviceID(secret, deviceID string) string {
	if secret == "" || deviceID == "" {
		return ""
	}
	mac := hmac.New(sha256.New, []byte(secret))
	_, _ = mac.Write([]byte("det-device-v1:"))
	_, _ = mac.Write([]byte(deviceID))
	return hex.EncodeToString(mac.Sum(nil))
}

// LimitGuard enforces the IP and device daily quotas. A nil guard is a no-op,
// which keeps unit tests and the memory-only development server independent
// from the database.
type LimitGuard struct {
	repo   repository.LimitRepository
	secret string
	now    func() time.Time
}

func NewLimitGuard(repo repository.LimitRepository, secret string) *LimitGuard {
	return &LimitGuard{repo: repo, secret: secret, now: time.Now}
}

// HashDeviceID hashes a device header with the guard's configured secret.
// Handlers never see the secret themselves.
func (g *LimitGuard) HashDeviceID(deviceID string) string {
	if g == nil {
		return ""
	}
	return HashDeviceID(g.secret, deviceID)
}

// limitSettings resolves the environment configuration for a scope. 0 means
// unlimited, matching the existing DAILY_* variables.
func limitSettings(scope string) (perIP, perDevice int) {
	switch scope {
	case LimitScopeMock:
		return envLimit("DAILY_MOCK_LIMIT_PER_IP", 10), envLimit("DAILY_MOCK_LIMIT_PER_DEVICE", 5)
	case LimitScopeSpeaking:
		return envLimit("DAILY_SPEAKING_LIMIT_PER_IP", 60), envLimit("DAILY_SPEAKING_LIMIT_PER_DEVICE", 40)
	case LimitScopeAuth:
		return envLimit("DAILY_AUTH_LIMIT_PER_IP", 20), envLimit("DAILY_AUTH_LIMIT_PER_DEVICE", 10)
	default:
		return 0, 0
	}
}

// Allow atomically consumes one slot from the IP quota and then from the
// device quota. The IP quota is checked first so a caller that rotates the
// device header is still bounded by the network address.
func (g *LimitGuard) Allow(ctx context.Context, scope, ip, deviceHash string) error {
	if g == nil || g.repo == nil {
		return nil
	}
	perIP, perDevice := limitSettings(scope)
	window := g.now().UTC()

	if perIP > 0 && ip != "" {
		used, allowed, err := g.repo.ConsumeDaily(ctx, scope+":ip", ip, window, perIP)
		if err != nil {
			return fmt.Errorf("daily limit store: %w", err)
		}
		if !allowed {
			return &LimitExceededError{Scope: scope, Kind: "ip", Limit: perIP, Used: used}
		}
	}
	if perDevice > 0 && deviceHash != "" {
		used, allowed, err := g.repo.ConsumeDaily(ctx, scope+":device", deviceHash, window, perDevice)
		if err != nil {
			return fmt.Errorf("daily limit store: %w", err)
		}
		if !allowed {
			return &LimitExceededError{Scope: scope, Kind: "device", Limit: perDevice, Used: used}
		}
	}
	return nil
}

// SecondsUntilDailyReset is used for the Retry-After header.
func SecondsUntilDailyReset() int {
	return int(time.Until(startOfUTCDay().Add(24 * time.Hour)).Seconds())
}
